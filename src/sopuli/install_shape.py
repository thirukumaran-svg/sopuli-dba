"""What this machine can serve, and what this config asked for (ADR-006 E6).

    **`doctor` always reports install shape (E6).** Which backends are
    installed, which are configured, and where the two disagree -- listed every
    run, not only on mismatch. `doctor`'s question is "can I reach my vaults",
    and its output is audit evidence as often as it is a diagnostic; a section
    that appears only when something is wrong cannot be quoted as proof that
    nothing was.

**This is not what the two diagnostics already do.**
:func:`~sopuli.diagnostics.backend_diagnostics` and
:func:`~sopuli.diagnostics.driver_diagnostics` emit one warning per configured
backend or driver that is missing, so a healthy install produces nothing at all
-- which is precisely the shape E6 rules out. They answer *what is wrong*; this
answers *what is there*, and a run that said nothing could never be quoted as
evidence that everything was installed.

**Every registry entry appears, configured or not.** That is what makes the
third direction reportable -- installed and *not* configured, which nothing else
in the tool looks at. The gap between what a machine can do and what it was
asked to do is worth seeing before somebody is troubleshooting inside it.

**Asking must not import**, which is ADR-006 rule 3 and the reason
:func:`sopuli.extras.installed` exists at all. A survey that imported every
configured client to find out whether it was there would break the rule it is
reporting on: an SDK's import can read a config file or reach a metadata
service, and this runs on every ``doctor``. Everything below asks
:func:`importlib.util.find_spec`, which stops at the path.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from dataclasses import dataclass

from sopuli.config.model import Config
from sopuli.driver.registry import DRIVERS, DatabaseDriver
from sopuli.extras import installed
from sopuli.store.registry import BACKENDS, Backend

#: The client is present and this build has a module that uses it. The only
#: status a command can actually resolve.
INSTALLED = "installed"

#: This build has the module and the client is not on this machine. `pip` fixes
#: it, and :attr:`Component.install_command` is the line -- the same condition
#: :class:`~sopuli.store.registry.BackendNotInstalledError` reports.
NOT_INSTALLED = "not_installed"

#: This build has no module for it. Nothing the operator installs fixes it, so a
#: row in this state never carries an install command -- the same distinction
#: :class:`~sopuli.store.registry.BackendNotImplementedError` exists to draw, and
#: the expensive one to get wrong: sending somebody to `pip` forever for
#: something `pip` cannot supply.
NOT_IMPLEMENTED = "not_implemented"

#: Every value :attr:`Component.status` can take. A closed enum in the run
#: schema, so a consumer branches on it rather than on a boolean that would have
#: had to collapse the last two rows into one.
STATUSES = (INSTALLED, NOT_INSTALLED, NOT_IMPLEMENTED)


@dataclass(frozen=True)
class Component:
    """One registry entry, and what this machine and this config say about it.

    ``configured`` holds the **names of the config entries that ask for it** --
    the ``vaults:`` keys for a backend, the expanded target names for a driver.
    Both are carried, and the serialiser publishes them differently
    (:mod:`sopuli.output.install_view`): a store is written out by hand and its
    name is the thing to go and look at, while targets are generated by the
    dozen from one ``target_sets:`` entry and are already listed in full in
    ``targets[]``. Keeping the model complete and letting the view decide what to
    print is the arrangement the rest of the output layer already uses.

    ``install_command`` is present only where one exists and would help, which is
    :data:`NOT_INSTALLED` alone. An installed component does not need it, and an
    unimplemented one has no such command however much its name suggests
    otherwise.
    """

    name: str
    status: str
    configured: tuple[str, ...] = ()
    install_command: str | None = None


@dataclass(frozen=True)
class InstallShape:
    """The whole survey: every backend and every driver this build knows of."""

    backends: tuple[Component, ...]
    drivers: tuple[Component, ...]

    @property
    def missing(self) -> tuple[Component, ...]:
        """Configured components this machine cannot serve, in report order.

        The predicate behind "a configured-but-uninstalled backend or driver is a
        `doctor` failure" (E4/E6). Both non-installed statuses count: from the
        estate's point of view a backend nobody has written and a client nobody
        installed are the same outage, and only the remedy differs -- which is
        what ``status`` and ``install_command`` are there to say.
        """
        return tuple(
            component
            for component in (*self.backends, *self.drivers)
            if component.configured and component.status != INSTALLED
        )


def survey(
    config: Config,
    *,
    backends: Mapping[str, Backend] = BACKENDS,
    drivers: Mapping[str, DatabaseDriver] = DRIVERS,
) -> InstallShape:
    """Every backend and driver, what this machine has, and what asked for it.

    The registries are parameters rather than read from the module globals, so
    that the disagreeing cases can be tested at all. The developer environment is
    ``sopuli-dba[all]`` and three of the four backends are unwritten, so the two
    states that actually matter -- configured and not installed, installed and
    not configured -- are unreachable from the real tables on the machine this is
    developed on, and a survey that could only ever be exercised in its healthy
    shape is a survey nobody has checked.
    """
    declared_vaults: dict[str, list[str]] = {}
    for vault in config.vaults:
        declared_vaults.setdefault(vault.type, []).append(vault.name)

    declared_targets: dict[str, list[str]] = {}
    for target in config.expanded_targets:
        declared_targets.setdefault(target.target.type, []).append(target.name)

    return InstallShape(
        backends=tuple(
            _component(name, entry, declared_vaults.get(name, ()))
            for name, entry in sorted(backends.items())
        ),
        drivers=tuple(
            _component(name, entry, declared_targets.get(name, ()))
            for name, entry in sorted(drivers.items())
        ),
    )


def _component(name: str, entry: Backend | DatabaseDriver, configured: Sequence[str]) -> Component:
    """One row, for either registry -- they carry the same three fields.

    :class:`~sopuli.store.registry.Backend` and
    :class:`~sopuli.driver.registry.DatabaseDriver` are deliberately separate
    types, with separate error classes and separate sentences (#170), and this is
    the one place where what they have in common is all that is being asked:
    where the module is, what installs its client, and what that client is
    called. Naming those three here is cheaper than a shared base class would be
    everywhere else.
    """
    status = _status(entry)
    return Component(
        name=name,
        status=status,
        configured=tuple(configured),
        install_command=entry.install_command if status == NOT_INSTALLED else None,
    )


def _status(entry: Backend | DatabaseDriver) -> str:
    """Which of the three this is, asked without importing anything.

    Order matters, and it is the order :func:`sopuli.store.registry.resolve`
    already fails in. A build with no module for a backend cannot serve it
    whatever `pip` has put on the machine, so that is asked first -- otherwise
    ``oci``, which has an extra and no module yet, would report itself installed
    on a developer machine that has the SDK and still refuse at connect time.
    """
    if not installed((entry.module,)):
        return NOT_IMPLEMENTED
    if entry.extra is not None and not installed(entry.provides):
        return NOT_INSTALLED
    return INSTALLED
