"""Expanding ``target_sets:`` into the targets a run will actually touch (§4).

:mod:`sopuli.config.target_sets` validates that a set *is* one -- exactly one
outer dimension, at most one inner one. This is the other half: rendering that
template into concrete targets. Three §10 rules live here and nowhere else,
because none of them can be seen before a name exists:

* a ``name`` template that renders the same name twice
* a ``{placeholder}`` with nothing to resolve from -- an error, never an empty
  string
* an ``overrides`` key naming a target the set does not generate, which is what
  catches a rename

The result is the estate: every explicit target, then every generated one, each
wrapped in an :class:`~sopuli.config.model.ExpandedTarget` that remembers where
it came from. It is built once, at load, and everything downstream reads it --
selection, plan output, ``config show --resolved`` -- so the set of targets the
tool acts on is the set it prints (invariant 5).

Substitution is deliberately not a template language (C7). ``{name}`` is looked
up in a flat scope of dimension values and variables, there is no expression
syntax, and there is no way to escape a literal brace. A DSN or an account name
has no reason to contain one, and an escape is one more thing to get wrong in
the file that decides where production passwords are written.

No I/O of any kind: expansion is text substitution over what the file already
says (``04-testing.md`` §4).
"""

from __future__ import annotations

from collections.abc import Iterator
from dataclasses import dataclass

from sopuli.config.errors import ROOT, ConfigError, KeyPath
from sopuli.config.model import (
    AdminAuth,
    AdminCredential,
    Config,
    DimensionValue,
    ExpandedTarget,
    Pairs,
    Safety,
    Target,
    TargetOracle,
    TargetPatch,
    TargetSet,
)
from sopuli.config.secret_refs import parse_secret_ref
from sopuli.config.templates import substitute

#: The label naming the set a target was generated by. Part of the selection
#: vocabulary rather than a debugging aid -- §4's own group example matches on it
#: (``match: { target_set: appdb, env: dev }``).
TARGET_SET_LABEL = "target_set"

#: What an unresolved token in a target set is measured against. See §4 rule 4.
_SCOPE = (
    "a placeholder resolves from the dimension and the variables of the "
    "`for_each:` value being rendered (§4)"
)

_TARGETS = ROOT.key("targets")
_TARGET_SETS = ROOT.key("target_sets")

#: How many generated names to list before summarising. An estate of 35 PDBs
#: makes a full list unreadable, and the first few are enough to see the shape a
#: mistyped override was aiming at.
_NAMES_SHOWN = 5


def expand_targets(config: Config) -> tuple[ExpandedTarget, ...]:
    """The whole estate: explicit targets in document order, then generated ones.

    Explicit first because that is the order the file reads in, and because a
    name collision between an explicit target and a generated one should be
    reported against the set -- the set is what changes when a tenant is added.
    """
    expanded = [
        ExpandedTarget(target=target, index=index) for index, target in enumerate(config.targets)
    ]
    for target_set in config.target_sets:
        expanded.extend(_expand(target_set))

    _reject_duplicate_names(expanded)
    return tuple(expanded)


def declared_at(expanded: ExpandedTarget, field: str | None = None) -> KeyPath:
    """Where in the document this target -- or one of its keys -- was written.

    A generated target points at the set that generated it. There is no key in
    the file for ``appdb-qa-delta``, and naming ``target_sets.appdb`` is what
    sends someone to lines they can actually edit.

    Naming a ``field`` is what makes that precise enough to act on. A key an
    override patched was written in the override, and reporting it against the
    template would point at the one place the value is spelled correctly --
    exactly the wrong line when the template's `vault:` is fine and the
    exception's is a typo.
    """
    at = _location(expanded)
    if field is not None and field in expanded.patched and expanded.target_set is not None:
        at = at.key("overrides").key(expanded.name)
    return at if field is None else at.key(field)


def _location(expanded: ExpandedTarget) -> KeyPath:
    if expanded.target_set is not None:
        return _TARGET_SETS.key(expanded.target_set)
    if expanded.index is None:  # pragma: no cover - an explicit target always has one
        return _TARGETS
    return _TARGETS.index(expanded.index)


# ------------------------------------------------------------ combinations ---


@dataclass(frozen=True)
class _Combination:
    """One point in the dimension space, and what it renders from.

    ``variables`` is the flat scope substitution looks names up in: the outer
    dimension, the scalars written beside it, and the inner dimension's current
    value. ``labels`` is the subset of that which §4 says becomes labels --
    dimensions only, not every variable, because ``host`` and ``db_domain``
    describe how to connect rather than which population a target belongs to.
    """

    variables: dict[str, str]
    labels: Pairs

    def describe(self) -> str:
        """``env=qa, tenant=delta`` -- how to name this combination in an error."""
        return ", ".join(f"{key}={value}" for key, value in self.labels if key != TARGET_SET_LABEL)


def _combinations(target_set: TargetSet, *, at: KeyPath) -> Iterator[_Combination]:
    dimension = target_set.for_each.dimension
    at_dimension = at.key("for_each").key(dimension)

    for value in target_set.for_each.values:
        _reject_shadowing(dimension, value, at=at_dimension.key(value.value))
        variables = {**dict(value.variables), dimension: value.value}
        labels = ((TARGET_SET_LABEL, target_set.name), (dimension, value.value))

        if value.inner is None:
            # §4 rule 2: a value with no list variable generates a single target.
            yield _Combination(variables=variables, labels=labels)
            continue

        for inner in value.inner.values:
            yield _Combination(
                variables={**variables, value.inner.name: inner},
                labels=(*labels, (value.inner.name, inner)),
            )


def _reject_shadowing(dimension: str, value: DimensionValue, *, at: KeyPath) -> None:
    """A variable may not be named after the dimension it is written under.

    ``for_each: { env: { dev: { env: production } } }`` gives ``{env}`` two
    meanings in one scope, and whichever won would be an arbitrary choice that
    then decides a rendered secret path. Refusing costs one rename; guessing
    costs a target that reads correctly and points somewhere else.
    """
    names = [name for name, _ in value.variables]
    if value.inner is not None:
        names.append(value.inner.name)
    if dimension not in names:
        return
    raise ConfigError(
        f"variable {dimension!r} has the same name as the dimension it is written under",
        at=at.key(dimension),
        hint=f"`{{{dimension}}}` already renders as {value.value!r} here -- rename the variable",
    )


# ------------------------------------------------------------- one set ---


def _expand(target_set: TargetSet) -> list[ExpandedTarget]:
    at = _TARGET_SETS.key(target_set.name)
    generated: dict[str, tuple[Target, _Combination]] = {}

    for combination in _combinations(target_set, at=at):
        target = _render_target(target_set.template, combination, at=at)
        if target.name in generated:
            _, first = generated[target.name]
            raise ConfigError(
                f"target set {target_set.name!r} renders the name {target.name!r} twice",
                at=at.key("name"),
                hint=(
                    f"{first.describe()} and {combination.describe()} both render it -- "
                    "put the variable that distinguishes them into `name`"
                ),
            )
        generated[target.name] = (target, combination)

    patched = _apply_overrides(target_set, generated, at=at)
    return [
        ExpandedTarget(
            target=target,
            target_set=target_set.name,
            patched=patched.get(name, ()),
        )
        for name, (target, _) in generated.items()
    ]


# --------------------------------------------------------------- rendering ---


def _render_target(template: Target, combination: _Combination, *, at: KeyPath) -> Target:
    """The template with every placeholder resolved.

    ``type``, ``oracle.scope`` and ``admin.auth.method`` are absent from this
    because they are closed sets: :mod:`sopuli.config.targets` reads them through
    :func:`~sopuli.config.fields.choice`, so a ``{placeholder}`` in one was
    already refused when the set was built. Every other string field is
    rendered, including label keys and the addresses inside ``admin.auth`` -- a
    field that expansion skipped would keep its braces and reach a connection
    string or a vault intact, which is the failure §10's "never an empty string"
    rule is guarding against.
    """
    variables = combination.variables
    return Target(
        name=_substitute(template.name, variables, at=at.key("name")),
        type=template.type,
        dsn=_substitute(template.dsn, variables, at=at.key("dsn")),
        environment=_maybe(template.environment, variables, at=at.key("environment")),
        vault=_maybe(template.vault, variables, at=at.key("vault")),
        admin=_render_admin(template.admin, variables, at=at.key("admin")),
        oracle=_render_oracle(template.oracle, variables, at=at.key("oracle")),
        labels=_render_labels(template.labels, combination, at=at.key("labels")),
        safety=_render_safety(template.safety, variables, at=at.key("safety")),
    )


def _render_admin(
    admin: AdminCredential | None, variables: dict[str, str], *, at: KeyPath
) -> AdminCredential | None:
    if admin is None:
        return None
    return AdminCredential(
        username=_maybe(admin.username, variables, at=at.key("username")),
        auth=_render_admin_auth(admin.auth, variables, at=at.key("auth")),
    )


def _render_admin_auth(
    auth: AdminAuth | None, variables: dict[str, str], *, at: KeyPath
) -> AdminAuth | None:
    """The admin credential's own addresses, rendered like every other string.

    ``method`` is not, because it is a closed set -- a ``{placeholder}`` there was
    refused when the set was built. Everything else it carries names *where* the
    credential is: a ref like ``ops/sopuli/{env}/admin#password`` and a variable
    name like ``SOPULI_DB_ADMIN_PW_{env}``. Leaving either unrendered would be the
    one string in the estate that reaches a vault with its braces intact, which is
    exactly what §4 rule 4 forbids.

    A ref is rendered as text and re-parsed, because a token's *value* can change
    the ref's structure -- a ``{tenant}`` holding a ``#`` is a different field.
    §7 says that is the one thing the load-time check cannot see, so the check has
    to happen again once the value is known.
    """
    if auth is None:
        return None
    ref = None if auth.secret is None else str(auth.secret)
    rendered = _maybe(ref, variables, at=at.key("secret"))
    return AdminAuth(
        method=auth.method,
        secret=None if rendered is None else parse_secret_ref(rendered, at=at.key("secret")),
        password_env=_maybe(auth.password_env, variables, at=at.key("password_env")),
    )


def _render_oracle(oracle: TargetOracle, variables: dict[str, str], *, at: KeyPath) -> TargetOracle:
    return TargetOracle(
        scope=oracle.scope,
        container=_maybe(oracle.container, variables, at=at.key("container")),
    )


def _render_safety(
    safety: Safety | None, variables: dict[str, str], *, at: KeyPath
) -> Safety | None:
    if safety is None:
        return None
    where = at.key("confirm_environments")
    return Safety(
        max_targets=safety.max_targets,
        confirm_environments=tuple(
            _substitute(name, variables, at=where.index(index))
            for index, name in enumerate(safety.confirm_environments)
        ),
        readonly=safety.readonly,
    )


def _render_labels(labels: Pairs, combination: _Combination, *, at: KeyPath) -> Pairs:
    """The dimension labels §4 attaches, plus whatever the template writes itself.

    A template label that collides with a dimension is refused rather than
    resolved either way round. Silently winning would make the file say one thing
    and the estate another; silently losing would drop a label a group is
    matching on. Writing the same value twice -- ``labels: { env: "{env}" }`` --
    is harmless and allowed, because there is no disagreement to report.
    """
    merged = dict(combination.labels)
    for key, value in labels:
        # Both halves are reported against the entry as written, `labels.{env}`:
        # the rendered key is not in the file, so it is not a location.
        rendered_key = _substitute(key, combination.variables, at=at.key(key))
        rendered_value = _substitute(value, combination.variables, at=at.key(key))
        if rendered_key in merged and merged[rendered_key] != rendered_value:
            raise ConfigError(
                f"label {rendered_key!r} is already {merged[rendered_key]!r} on every target "
                f"this set generates",
                at=at.key(key),
                hint=(
                    "a generated target carries `target_set` and its dimension values as "
                    "labels (§4) -- rename this one, or drop it and let the dimension supply it"
                ),
            )
        merged[rendered_key] = rendered_value
    return tuple(sorted(merged.items()))


def _maybe(text: str | None, variables: dict[str, str], *, at: KeyPath) -> str | None:
    """Render an optional field, keeping absent as absent."""
    return None if text is None else _substitute(text, variables, at=at)


def _substitute(text: str, variables: dict[str, str], *, at: KeyPath) -> str:
    """Render one template string in this combination's scope.

    The mechanism is shared with secret refs (:mod:`sopuli.config.templates`);
    only the sentence naming where the values come from differs.
    """
    return substitute(text, variables, at=at, source=_SCOPE)


# --------------------------------------------------------------- overrides ---


def _apply_overrides(
    target_set: TargetSet,
    generated: dict[str, tuple[Target, _Combination]],
    *,
    at: KeyPath,
) -> dict[str, tuple[str, ...]]:
    """Patch generated targets in place, and report which keys each patch wrote.

    §4 rule 5: overrides are found by *rendered* name, after generation. An
    override that matches nothing is an error rather than a no-op -- §10 says so
    explicitly, because the way this fires in practice is a template being
    renamed and the exceptions quietly ceasing to apply.

    A patch is rendered in the same scope as the target it patches. §2's
    overrides are literal, but a placeholder left unrendered here would be the
    one string in the estate that reaches a DSN with its braces intact.

    The keys are returned rather than a yes/no, because a value's location is
    the line that wrote it: see :func:`declared_at`.
    """
    at_overrides = at.key("overrides")
    patched: dict[str, tuple[str, ...]] = {}

    for name, patch in target_set.overrides:
        if name not in generated:
            raise ConfigError(
                f"override {name!r} names no target that {target_set.name!r} generates",
                at=at_overrides.key(name),
                hint=_generated_hint(generated),
            )
        target, combination = generated[name]
        generated[name] = (
            _patch_target(target, patch, combination, at=at_overrides.key(name)),
            combination,
        )
        patched[name] = _patched_keys(patch)

    return patched


def _patched_keys(patch: TargetPatch) -> tuple[str, ...]:
    """Which target keys this patch writes, sorted.

    ``labels`` is the one measured by content rather than by presence: it is a
    tuple with an empty default rather than an optional, so "absent" and "given"
    are the same value.
    """
    given = {
        "type": patch.type is not None,
        "dsn": patch.dsn is not None,
        "environment": patch.environment is not None,
        "vault": patch.vault is not None,
        "admin": patch.admin is not None,
        "oracle": patch.oracle is not None,
        "labels": bool(patch.labels),
        "safety": patch.safety is not None,
    }
    return tuple(sorted(key for key, written in given.items() if written))


def _generated_hint(generated: dict[str, tuple[Target, _Combination]]) -> str:
    names = sorted(generated)
    shown = ", ".join(names[:_NAMES_SHOWN])
    more = f", ... ({len(names)} in all)" if len(names) > _NAMES_SHOWN else ""
    return (
        f"generated: {shown}{more} -- an override that stops matching is usually "
        "a renamed `name` template"
    )


def _patch_target(
    target: Target, patch: TargetPatch, combination: _Combination, *, at: KeyPath
) -> Target:
    """Apply one override. Absent keys keep the generated value.

    Nested blocks merge key by key rather than replacing wholesale, so
    ``admin: { username: X }`` does not silently drop the ``auth:`` the template
    set. ``name`` is not patchable: it is the key this patch was found by.

    ``safety:`` merges the same way, and that is not a hole in invariant 10 --
    §9 resolves the effective safety by taking the *safest* of all layers, so a
    relaxation written here still cannot relax what the run ends up with. That
    resolution belongs to the precedence work; this only decides what the target
    layer says.
    """
    variables = combination.variables
    return Target(
        name=target.name,
        type=target.type if patch.type is None else patch.type,
        dsn=(
            target.dsn if patch.dsn is None else _substitute(patch.dsn, variables, at=at.key("dsn"))
        ),
        environment=(
            target.environment
            if patch.environment is None
            else _substitute(patch.environment, variables, at=at.key("environment"))
        ),
        vault=(
            target.vault
            if patch.vault is None
            else _substitute(patch.vault, variables, at=at.key("vault"))
        ),
        admin=_patch_admin(target.admin, patch.admin, variables, at=at.key("admin")),
        oracle=_patch_oracle(target.oracle, patch.oracle, variables, at=at.key("oracle")),
        labels=_patch_labels(target.labels, patch.labels, variables, at=at.key("labels")),
        safety=_patch_safety(target.safety, patch.safety, variables, at=at.key("safety")),
    )


def _patch_admin(
    current: AdminCredential | None,
    patch: AdminCredential | None,
    variables: dict[str, str],
    *,
    at: KeyPath,
) -> AdminCredential | None:
    """``admin:`` merges key by key -- but ``auth:`` replaces as a whole.

    The two halves of ``admin:`` are independent: patching the username of a target
    reached through a wallet is a sentence that makes sense. An ``auth:`` block is
    not independent of itself -- its keys belong to its ``method:`` -- so merging
    ``{ method: prompt }`` over ``{ method: vault, secret: ... }`` would leave a
    prompt carrying a ref that no longer means anything. An override that changes
    the method states the whole credential source, which is one line either way.
    """
    if patch is None:
        return current
    base = current if current is not None else AdminCredential()
    username = _maybe(patch.username, variables, at=at.key("username"))
    return AdminCredential(
        username=base.username if username is None else username,
        auth=(
            base.auth
            if patch.auth is None
            else _render_admin_auth(patch.auth, variables, at=at.key("auth"))
        ),
    )


def _patch_oracle(
    current: TargetOracle,
    patch: TargetOracle | None,
    variables: dict[str, str],
    *,
    at: KeyPath,
) -> TargetOracle:
    if patch is None:
        return current
    container = _maybe(patch.container, variables, at=at.key("container"))
    return TargetOracle(
        scope=current.scope if patch.scope is None else patch.scope,
        container=current.container if container is None else container,
    )


def _patch_labels(current: Pairs, patch: Pairs, variables: dict[str, str], *, at: KeyPath) -> Pairs:
    """Labels merge; a patch may add or change one but not clear the rest.

    Replacing the whole mapping would drop the dimension labels §4 attaches, and
    with them the ``--select env=qa`` that found this target in the first place.
    A patch *may* override a dimension label -- the target really is the
    exception, and stating that is the point of an override.
    """
    merged = dict(current)
    for key, value in patch:
        rendered_key = _substitute(key, variables, at=at.key(key))
        merged[rendered_key] = _substitute(value, variables, at=at.key(key))
    return tuple(sorted(merged.items()))


def _patch_safety(
    current: Safety | None,
    patch: Safety | None,
    variables: dict[str, str],
    *,
    at: KeyPath,
) -> Safety | None:
    if patch is None:
        return current
    base = current if current is not None else Safety()
    where = at.key("confirm_environments")
    confirm = tuple(
        _substitute(name, variables, at=where.index(index))
        for index, name in enumerate(patch.confirm_environments)
    )
    return Safety(
        max_targets=base.max_targets if patch.max_targets is None else patch.max_targets,
        confirm_environments=confirm if confirm else base.confirm_environments,
        readonly=base.readonly if patch.readonly is None else patch.readonly,
    )


# ------------------------------------------------------------ uniqueness ---


def _reject_duplicate_names(expanded: list[ExpandedTarget]) -> None:
    """§4 rule 3, across the whole estate rather than one set.

    :mod:`sopuli.config.targets` already rejects two explicit targets sharing a
    name; this catches the two cases it cannot see -- a generated name colliding
    with an explicit one, and two sets generating the same name. The consequence
    is the same either way: ``--target`` becomes ambiguous, and one of the two
    shadows the other everywhere a name is looked up.
    """
    seen: dict[str, ExpandedTarget] = {}
    for candidate in expanded:
        first = seen.setdefault(candidate.name, candidate)
        if first is candidate:
            continue
        raise ConfigError(
            f"duplicate target name {candidate.name!r}",
            at=declared_at(candidate, "name"),
            hint=f"already declared at {declared_at(first)}",
        )
