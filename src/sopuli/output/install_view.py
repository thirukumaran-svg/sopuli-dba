"""The run document's ``install`` section, and what ``doctor`` prints (#214).

ADR-006 E6 asks for three facts and the third is the one nothing else reports:
which components are installed, which are configured, and **what is installed
and not configured**. All three fall out of listing every registry entry with
its status, rather than of three separate lookups that could disagree.

**A new top-level section rather than a member of ``targets[]``.** Install shape
is neither per-target nor per-vault -- it is a property of the machine, and the
run document had no section shaped like that. Squeezing it into the per-target
array would have repeated one machine fact once per target, and made a
twenty-one PDB estate say the same thing twenty-one times. Adding a section is
the minor rule (``03-json-output.md`` §8), the same one #182 followed when
``targets[]`` itself was the alternative to widening ``result``.

**Emitted whole, empty arrays included**, which is the same argument
``privileges`` follows: a section that appeared only when something was wrong
could not be quoted as evidence that nothing was. So a component nobody
configured still gets a row, and it says ``vaults: []`` rather than being left
out.

**Backends name their config entries and drivers count theirs**, which is the
one asymmetry here and it is deliberate. A store is written out by hand, there
are a handful of them, and its name is the thing to go and look at. Targets are
generated by the dozen from one ``target_sets:`` entry, and every one of them is
already listed in full in ``targets[]`` -- so naming them again here would be a
second copy of a fact the same document already carries. It is the same reasoning
:func:`~sopuli.diagnostics.driver_diagnostics` uses to warn once per driver type
rather than once per target.
"""

from __future__ import annotations

from typing import Any

from sopuli.install_shape import Component, InstallShape
from sopuli.output.table import Column, render_table


def build(shape: InstallShape) -> dict[str, Any]:
    """The ``install`` section, as ``sopuli-run-1.16.schema.json`` describes it."""
    return {
        "backends": [
            {**_component(component), "vaults": list(component.configured)}
            for component in shape.backends
        ],
        "drivers": [
            {**_component(component), "targets": len(component.configured)}
            for component in shape.drivers
        ],
    }


def _component(component: Component) -> dict[str, Any]:
    """The two fields both kinds carry.

    ``install_command`` is omitted rather than nulled when there is none, which
    is what the rest of this module's document already does -- and here the
    absence carries the meaning that matters: a row with no install line is a row
    `pip` cannot help with, whether because it is already installed or because
    this build has no module for it. ``status`` is what separates those two, and
    it is always present.
    """
    found: dict[str, Any] = {"name": component.name, "status": component.status}
    if component.install_command is not None:
        found["install_command"] = component.install_command
    return found


def _targets(count: int) -> str:
    """``-``, ``1 target``, ``21 targets``. ASCII throughout, which is P4's rule."""
    if count == 0:
        return "-"
    return "1 target" if count == 1 else f"{count} targets"


def render(shape: InstallShape) -> list[str]:
    """The text form: one table, backends above drivers.

    One table rather than two, because the reader's question spans both -- *can
    this machine do what the file asks* -- and two tables of three rows each,
    with identical headings, would be two places to look for one answer. The KIND
    column is what keeps them distinguishable, and it is also what makes the
    configured column readable while the two halves count different things.
    """
    columns = [
        Column("KIND"),
        Column("NAME"),
        Column("STATUS"),
        Column("CONFIGURED"),
    ]
    rows = [
        ["backend", one.name, one.status, ", ".join(one.configured) or "-"]
        for one in shape.backends
    ]
    rows.extend(
        [
            "driver",
            one.name,
            one.status,
            # A count, and the word, because "21" alone in a column shared with
            # store names reads as an identifier rather than a quantity.
            _targets(len(one.configured)),
        ]
        for one in shape.drivers
    )

    lines = ["install"]
    lines.extend(f"  {line}" for line in render_table(columns, rows))
    for one in (*shape.backends, *shape.drivers):
        if one.install_command is not None and one.configured:
            lines.append(f"  {one.name}: install it with:  {one.install_command}")
    lines.append("")
    return lines
